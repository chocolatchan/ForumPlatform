"""Task 027-H1-R2: full image decoding and normalization regression tests.

These tests deliberately use real compressed bitstreams generated by Pillow,
plus malformed files whose container headers are plausible but whose pixel
data is corrupt. They exercise the validator directly, without HTTP.
"""

import io

import pytest
from PIL import Image

from src.services.content.storage import (
    MAX_FILE_SIZE_BYTES,
    MAX_IMAGE_HEIGHT,
    MAX_IMAGE_PIXELS,
    MAX_IMAGE_WIDTH,
    validate_and_normalize_image,
)


def _encode(image: Image.Image, fmt: str, **kwargs: object) -> bytes:
    buf = io.BytesIO()
    image.save(buf, format=fmt, **kwargs)
    return buf.getvalue()


def _assert_normalized(data: bytes, expected_mime: str, expected_format: str) -> None:
    ok, mime, normalized, width, height = validate_and_normalize_image(data)
    assert ok is True, mime
    assert mime == expected_mime
    assert (width, height) == Image.open(io.BytesIO(data)).size
    decoded = Image.open(io.BytesIO(normalized))
    assert decoded.format == expected_format
    decoded.load()
    assert decoded.size == (width, height)


@pytest.mark.parametrize(
    ("fmt", "mime", "pil_format"),
    [
        ("PNG", "image/png", "PNG"),
        ("JPEG", "image/jpeg", "JPEG"),
        ("WEBP", "image/webp", "WEBP"),
    ],
)
def test_valid_formats_are_fully_decoded_and_normalized(fmt, mime, pil_format):
    data = _encode(Image.new("RGB", (64, 48), (12, 34, 56)), fmt)
    _assert_normalized(data, mime, pil_format)


def test_jpeg_exif_metadata_is_stripped_after_orientation():
    img = Image.new("RGB", (32, 16), (200, 10, 10))
    exif = Image.Exif()
    exif[0x0112] = 6  # rotate 90 clockwise
    data = _encode(img, "JPEG", exif=exif)

    ok, _, normalized, width, height = validate_and_normalize_image(data)
    assert ok is True
    assert (width, height) == (16, 32)
    assert Image.open(io.BytesIO(normalized)).getexif() == {}


@pytest.mark.parametrize("fmt", ["PNG", "JPEG", "WEBP"])
def test_corrupt_compressed_pixel_data_is_rejected(fmt):
    data = _encode(Image.new("RGB", (128, 128), (20, 40, 60)), fmt)

    if fmt == "JPEG":
        # Keep SOI and a valid EOI marker but truncate the entropy-coded scan.
        corrupt = data[: int(len(data) * 0.5)] + b"\xff\xd9"
    elif fmt == "PNG":
        corrupt = bytearray(data)
        corrupt[len(corrupt) // 2 : len(corrupt) // 2 + 16] = b"\xff" * 16
        corrupt = bytes(corrupt)
    else:
        corrupt = bytearray(data)
        corrupt[len(corrupt) // 2 : len(corrupt) // 2 + 16] = b"\xff" * 16
        corrupt = bytes(corrupt)

    ok, error, _, _, _ = validate_and_normalize_image(corrupt)
    assert ok is False
    assert "decoding failed" in error.lower() or "decompression" in error.lower()


def test_png_with_plausible_header_and_garbage_idat_is_rejected():
    valid = _encode(Image.new("RGB", (8, 8), (1, 2, 3)), "PNG")
    # Reuse the real signature and IHDR chunk, replace IDAT with garbage and
    # keep a structurally valid IEND. Only full decompression catches this.
    forged = valid[:33] + b"\x00\x00\x00\x08IDATgarbage!\x00\x00\x00\x00IEND\xaeB`\x82"
    ok, error, _, _, _ = validate_and_normalize_image(forged)
    assert ok is False
    assert "decoding failed" in error.lower()


def test_dimension_and_pixel_boundaries():
    assert MAX_IMAGE_WIDTH == MAX_IMAGE_HEIGHT == 8192

    at_width_limit = _encode(Image.new("RGB", (MAX_IMAGE_WIDTH, 1)), "PNG")
    ok, _, _, width, height = validate_and_normalize_image(at_width_limit)
    assert ok is True
    assert (width, height) == (MAX_IMAGE_WIDTH, 1)

    over_width_limit = _encode(Image.new("RGB", (MAX_IMAGE_WIDTH + 1, 1)), "PNG")
    ok, error, _, _, _ = validate_and_normalize_image(over_width_limit)
    assert ok is False
    assert "dimensions" in error.lower()

    at_pixel_limit = _encode(Image.new("RGB", (4000, 4000)), "PNG")
    ok, _, _, width, height = validate_and_normalize_image(at_pixel_limit)
    assert ok is True
    assert width * height == MAX_IMAGE_PIXELS

    over_pixel_limit = _encode(Image.new("RGB", (4096, 4000)), "PNG")
    ok, error, _, _, _ = validate_and_normalize_image(over_pixel_limit)
    assert ok is False
    assert "pixel count" in error.lower() or "decompression bomb" in error.lower()


def test_byte_size_limit_is_enforced_inside_validator():
    oversized = b"\x89PNG\r\n\x1a\n" + b"\x00" * MAX_FILE_SIZE_BYTES
    ok, error, _, _, _ = validate_and_normalize_image(oversized)
    assert ok is False
    assert "maximum allowed size" in error.lower()


def test_non_image_and_short_payloads_are_rejected():
    for payload in (b"", b"abc", b"<svg xmlns='http://www.w3.org/2000/svg'></svg>"):
        ok, _, _, _, _ = validate_and_normalize_image(payload)
        assert ok is False
